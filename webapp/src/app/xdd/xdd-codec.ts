export function parseXdd(xml: string): DeviceDocument {
  const source = xml.replace(/^\uFEFF/, '').trim();
  if (!source) {
    throw new XddFormatError('The file is empty.');
  }
  if (source.startsWith('[')) {
    throw new XddFormatError('EDS, DCF and other formats are not read. Only XDD is supported.');
  }

  const parsed = new DOMParser().parseFromString(source, 'text/xml');
  const root = parsed.documentElement;
  if (!root || root.localName === 'parsererror') {
    throw new XddFormatError('The XDD document is not valid XML.');
  }
  if (root.localName !== 'ISO15745ProfileContainer') {
    throw new XddFormatError('The file is not a CANopen XDD (ISO15745ProfileContainer).');
  }

  const document = createEmptyDocument();
  document.schemaVersion = schemaVersion(root);
  document.productName = '';
  document.versionSw = '';
  document.versionFw = '';
  document.versionHw = '';
  document.fileVersion = '';

  const parameters = new Map<string, Element>();
  for (const parameter of allElements(parsed, 'parameter')) {
    const id = parameter.getAttribute('uniqueID');
    if (id && !parameters.has(id)) {
      parameters.set(id, parameter);
    }
  }
  const typeDefs = new Map<string, DataTypeName | null>();
  for (const arrayElement of allElements(parsed, 'array')) {
    const id = arrayElement.getAttribute('uniqueID');
    if (id && !typeDefs.has(id)) {
      typeDefs.set(id, directType(arrayElement)?.type ?? null);
    }
  }

  for (const profile of children(root, 'ISO15745Profile')) {
    const body = child(profile, 'ProfileBody');
    if (!body) {
      continue;
    }
    const kind = profileKind(profile, body);
    if (kind === 'device') {
      readDeviceProfile(document, body);
    } else if (kind === 'network') {
      readNetworkProfile(document, body);
    }
  }

  for (const element of allElements(parsed, 'CANopenObject')) {
    const entry = readNetworkObject(element, parameters, typeDefs);
    if (!entry || document.objects.some((object) => object.index === entry.index)) {
      continue;
    }
    document.objects.push(entry);
  }

  if (document.objects.length === 0) {
    readParameterOnlyObjects(document, parameters, typeDefs);
  }

  sortDocument(document);
  if (!document.productName) {
    document.productName = 'Unnamed';
  }
  return document;
}

export function writeXdd(document: DeviceDocument, now = new Date()): string {
  const fileName = (document.fileName || 'device.xdd').replace(/^.*[\\/]/, '');
  const creation = stamp(document.fileCreationDate, document.fileCreationTime, now);
  const modification = stamp(document.fileModificationDate, document.fileModificationTime, now);
  const meta = fileAttributes(fileName, document, creation, modification);
  const objects = [...document.objects].sort((a, b) => a.index - b.index);
  const lines: string[] = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!--File is generated by CANopen Editor Web. Only the XDD device description (CiA 311) is read and written.-->',
    '<ISO15745ProfileContainer xmlns:xsd="http://www.w3.org/2001/XMLSchema" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns="http://www.canopen.org/xml/1.1">',
    '  <ISO15745Profile>',
    profileHeader('CANopen device profile', 'Device', 2),
    `    <ProfileBody xmlns:q1="http://www.canopen.org/xml/1.1" xsi:type="q1:ProfileBody_Device_CANopen" formatName="CANopen" formatVersion="1.0" ${meta} xmlns="">`,
    '      <q1:DeviceIdentity>',
    `        <q1:vendorName>${esc(document.vendorName)}</q1:vendorName>`,
    `        <q1:vendorID>${esc(document.vendorId)}</q1:vendorID>`,
    `        <q1:productName>${esc(document.productName)}</q1:productName>`,
    `        <q1:productID>${esc(document.productId)}</q1:productID>`,
  ];
  if (document.description) {
    lines.push(
      '        <q1:productText>',
      `          <description lang="en">${esc(document.description)}</description>`,
      '        </q1:productText>',
    );
  }
  if (document.orderCode) {
    lines.push(`        <q1:orderNumber>${esc(document.orderCode)}</q1:orderNumber>`);
  }
  lines.push(
    `        <q1:version versionType="SW">${esc(document.versionSw || '0')}</q1:version>`,
    `        <q1:version versionType="FW">${esc(document.versionFw || '0')}</q1:version>`,
    `        <q1:version versionType="HW">${esc(document.versionHw || '0')}</q1:version>`,
    '      </q1:DeviceIdentity>',
    '      <q1:DeviceFunction>',
    '        <q1:capabilities>',
    '          <q1:characteristicsList>',
    '            <q1:characteristic>',
    '              <q1:characteristicName>',
    '                <label lang="en">SW library</label>',
    '              </q1:characteristicName>',
    '              <q1:characteristicContent>',
    '                <label lang="en">CANopen Editor Web</label>',
    '              </q1:characteristicContent>',
    '            </q1:characteristic>',
    '          </q1:characteristicsList>',
    '        </q1:capabilities>',
    '      </q1:DeviceFunction>',
    '      <q1:ApplicationProcess>',
    '        <q1:dataTypeList>',
  );

  for (const object of objects) {
    if (object.objectType !== 'ARRAY' && object.objectType !== 'RECORD') {
      continue;
    }
    if (object.objectType === 'ARRAY') {
      const uid = `UID_ARR_${hex4(object.index)}`;
      const upper = Math.max(0, object.subObjects.length - 1);
      lines.push(
        `          <q1:array name="${esc(object.name)}" uniqueID="${uid}">`,
        `            <q1:subrange lowerLimit="0" upperLimit="${upper}" />`,
        `            <${typeTag(arrayElementType(object))} />`,
        '          </q1:array>',
      );
    } else {
      lines.push(`          <q1:struct name="${esc(object.name)}" uniqueID="UID_REC_${hex4(object.index)}">`);
      for (const sub of sortedSubs(object)) {
        lines.push(
          `            <q1:varDeclaration name="${esc(sub.name)}" uniqueID="UID_RECSUB_${hex4(object.index)}${hex2(sub.subIndex)}">`,
          `              <${typeTag(sub.dataType)} />`,
          '            </q1:varDeclaration>',
        );
      }
      lines.push('          </q1:struct>');
    }
  }

  lines.push('        </q1:dataTypeList>', '        <q1:parameterList>');
  for (const object of objects) {
    lines.push(...parameterLines(object, null, 5));
    if (object.objectType === 'ARRAY' || object.objectType === 'RECORD') {
      for (const sub of sortedSubs(object)) {
        lines.push(...parameterLines(sub, object, 5));
      }
    }
  }
  lines.push(
    '        </q1:parameterList>',
    '      </q1:ApplicationProcess>',
    '    </ProfileBody>',
    '  </ISO15745Profile>',
    '  <ISO15745Profile>',
    profileHeader('CANopen communication network profile', 'CommunicationNetwork', 2),
    `    <ProfileBody xmlns:q2="http://www.canopen.org/xml/1.1" xsi:type="q2:ProfileBody_CommunicationNetwork_CANopen" formatName="CANopen" formatVersion="1.0" ${meta} xmlns="">`,
    '      <ApplicationLayers>',
    '        <q2:CANopenObjectList>',
  );

  for (const object of objects) {
    const subs = sortedSubs(object);
    const complex = object.objectType === 'ARRAY' || object.objectType === 'RECORD';
    const attributes = [
      `index="${hex4(object.index)}"`,
      `name="${esc(object.name)}"`,
      `objectType="${OBJECT_TYPE_CODE[object.objectType]}"`,
    ];
    if (!complex) {
      attributes.push(`PDOmapping="${object.pdoMapping}"`);
    }
    attributes.push(`uniqueIDRef="UID_OBJ_${hex4(object.index)}"`);
    if (complex) {
      attributes.push(`subNumber="${subs.length}"`);
      lines.push(`          <CANopenObject ${attributes.join(' ')}>`);
      for (const sub of subs) {
        lines.push(
          `            <CANopenSubObject subIndex="${hex2(sub.subIndex)}" name="${esc(sub.name)}" objectType="7" PDOmapping="${sub.pdoMapping}" uniqueIDRef="UID_SUB_${hex4(object.index)}${hex2(sub.subIndex)}" />`,
        );
      }
      lines.push('          </CANopenObject>');
    } else {
      lines.push(`          <CANopenObject ${attributes.join(' ')} />`);
    }
  }

  lines.push('        </q2:CANopenObjectList>', '        <dummyUsage>');
  for (let index = 0; index < 7; index += 1) {
    const used = document.dummy[index] ? '1' : '0';
    lines.push(`          <dummy entry="Dummy000${index + 1}=${used}" />`);
  }
  lines.push('        </dummyUsage>', '      </ApplicationLayers>', '      <TransportLayers>', '        <PhysicalLayer>', '          <baudRate>');
  for (const option of BAUD_OPTIONS) {
    if (document.baudRates[option.key]) {
      lines.push(`            <supportedBaudRate value="${option.xml}" />`);
    }
  }
  lines.push('          </baudRate>', '        </PhysicalLayer>', '      </TransportLayers>', '      <NetworkManagement>');
  lines.push(`        <CANopenGeneralFeatures${generalAttributes(document)} />`);
  lines.push(`        <CANopenMasterFeatures${masterAttributes(document)} />`);
  lines.push(
    '      </NetworkManagement>',
    '    </ProfileBody>',
    '  </ISO15745Profile>',
    '</ISO15745ProfileContainer>',
    '',
  );
  return lines.join('\n');
}

function schemaVersion(root: Element): SchemaVersion {
  const namespace = root.namespaceURI ?? '';
  if (namespace.includes('/1.0')) {
    return '1.0';
  }
  if (namespace.includes('/1.1') || namespace === '') {
    return '1.1';
  }
  throw new XddFormatError(`The XDD namespace is not supported: ${namespace}`);
}

function readDeviceProfile(document: DeviceDocument, body: Element): void {
  readFileAttributes(document, body);
  const identity = child(body, 'DeviceIdentity');
  if (!identity) {
    return;
  }
  document.vendorName = directText(identity, 'vendorName');
  document.vendorId = directText(identity, 'vendorID');
  document.productName = directText(identity, 'productName');
  document.productId = directText(identity, 'productID');
  document.orderCode = directText(identity, 'orderNumber');
  const productText = child(identity, 'productText');
  if (productText) {
    document.description = directText(productText, 'description') || (productText.textContent ?? '').trim();
  }
  for (const version of children(identity, 'version')) {
    const kind = (version.getAttribute('versionType') ?? '').toUpperCase();
    const value = (version.textContent ?? '').trim();
    if (kind === 'SW') {
      document.versionSw = value;
    } else if (kind === 'FW') {
      document.versionFw = value;
    } else if (kind === 'HW') {
      document.versionHw = value;
    }
  }
}

function readNetworkProfile(document: DeviceDocument, body: Element): void {
  if (!document.fileName) {
    readFileAttributes(document, body);
  }
  for (const baud of allElements(body, 'supportedBaudRate')) {
    const value = baud.getAttribute('value') ?? '';
    const option = BAUD_OPTIONS.find((item) => item.xml === value);
    if (option) {
      document.baudRates[option.key] = true;
    }
  }
  const general = first(body, 'CANopenGeneralFeatures');
  if (general) {
    document.granularity = numberAttr(general, 'granularity', document.granularity);
    document.nrOfRxPdo = numberAttr(general, 'nrOfRxPDO', document.nrOfRxPdo);
    document.nrOfTxPdo = numberAttr(general, 'nrOfTxPDO', document.nrOfTxPdo);
    document.bootUpSlave = boolAttr(general, 'bootUpSlave', document.bootUpSlave);
    document.lssSlave = boolAttr(general, 'layerSettingServiceSlave', document.lssSlave);
    document.ngSlave = boolAttr(general, 'ngSlave', document.ngSlave);
    document.ngMaster = boolAttr(general, 'ngMaster', document.ngMaster);
    document.nrOfNgMonitoredNodes = numberAttr(general, 'NrOfNG_MonitoredNodes', document.nrOfNgMonitoredNodes);
    document.groupMessaging = boolAttr(general, 'groupMessaging', document.groupMessaging);
    document.dynamicChannels = numberAttr(general, 'dynamicChannels', 0) > 0;
  }
  const master = first(body, 'CANopenMasterFeatures');
  if (master) {
    document.bootUpMaster = boolAttr(master, 'bootUpMaster', document.bootUpMaster);
    document.lssMaster = boolAttr(master, 'layerSettingServiceMaster', document.lssMaster);
  }
  for (const dummy of allElements(body, 'dummy')) {
    const match = /Dummy(\d{4})=([01])/.exec(dummy.getAttribute('entry') ?? '');
    if (!match) {
      continue;
    }
    const index = Number(match[1]);
    if (index >= 1 && index <= 7) {
      document.dummy[index - 1] = match[2] === '1';
    }
  }
}

function readFileAttributes(document: DeviceDocument, body: Element): void {
  document.fileName = body.getAttribute('fileName') ?? document.fileName;
  document.fileVersion = body.getAttribute('fileVersion') ?? document.fileVersion;
  document.fileCreator = body.getAttribute('fileCreator') ?? document.fileCreator;
  document.fileCreationDate = body.getAttribute('fileCreationDate') ?? document.fileCreationDate;
  document.fileCreationTime = body.getAttribute('fileCreationTime') ?? document.fileCreationTime;
  document.fileModifiedBy = body.getAttribute('fileModifiedBy') ?? document.fileModifiedBy;
  document.fileModificationDate = body.getAttribute('fileModificationDate') ?? document.fileModificationDate;
  document.fileModificationTime = body.getAttribute('fileModificationTime') ?? document.fileModificationTime;
}

function readNetworkObject(
  element: Element,
  parameters: Map<string, Element>,
  typeDefs: Map<string, DataTypeName | null>,
): OdEntry | null {
  const index = parseHex(element.getAttribute('index'));
  if (index == null) {
    return null;
  }
  const entry = createEntry({
    index,
    name: element.getAttribute('name') ?? '',
    objectType: objectTypeFrom(element.getAttribute('objectType')),
    dataType: dataTypeFromAttribute(element.getAttribute('dataType')),
    access: 'read',
    pdoMapping: pdoFrom(element.getAttribute('PDOmapping')),
    defaultValue: element.getAttribute('defaultValue') ?? '',
    actualValue: element.getAttribute('actualValue') ?? '',
    lowLimit: element.getAttribute('lowLimit') ?? '',
    highLimit: element.getAttribute('highLimit') ?? '',
    denotation: element.getAttribute('denotation') ?? '',
    storageGroup: element.getAttribute('edseditor_extenstion_storagelocation') || 'RAM',
    flagsPdo: element.getAttribute('edseditor_extension_notifyonchange') === 'true',
  });
  const networkAccess = NETWORK_ACCESS[element.getAttribute('accessType') ?? ''];
  if (networkAccess) {
    entry.access = adjustAccess(networkAccess, entry.pdoMapping);
  }
  const parameterId = element.getAttribute('uniqueIDRef');
  if (parameterId && parameters.has(parameterId)) {
    applyParameter(entry, parameters.get(parameterId)!, typeDefs);
  }
  for (const subElement of children(element, 'CANopenSubObject')) {
    const subIndex = parseHex(subElement.getAttribute('subIndex'));
    if (subIndex == null || entry.subObjects.some((sub) => sub.subIndex === subIndex)) {
      continue;
    }
    const sub = createEntry({
      index,
      subIndex,
      name: subElement.getAttribute('name') ?? '',
      objectType: 'VAR',
      dataType: dataTypeFromAttribute(subElement.getAttribute('dataType')),
      access: 'read',
      pdoMapping: pdoFrom(subElement.getAttribute('PDOmapping')),
      defaultValue: subElement.getAttribute('defaultValue') ?? '',
      actualValue: subElement.getAttribute('actualValue') ?? '',
      lowLimit: subElement.getAttribute('lowLimit') ?? '',
      highLimit: subElement.getAttribute('highLimit') ?? '',
      denotation: subElement.getAttribute('denotation') ?? '',
    });
    const subAccess = NETWORK_ACCESS[subElement.getAttribute('accessType') ?? ''];
    if (subAccess) {
      sub.access = adjustAccess(subAccess, sub.pdoMapping);
    }
    const subId = subElement.getAttribute('uniqueIDRef');
    if (subId && parameters.has(subId)) {
      applyParameter(sub, parameters.get(subId)!, typeDefs);
    }
    if (!sub.name) {
      sub.name = `Sub ${hex2(subIndex)}`;
    }
    entry.subObjects.push(sub);
  }
  if (entry.objectType === 'VAR' && entry.subObjects.length > 0) {
    entry.objectType = 'RECORD';
  }
  return entry;
}

function readParameterOnlyObjects(
  document: DeviceDocument,
  parameters: Map<string, Element>,
  typeDefs: Map<string, DataTypeName | null>,
): void {
  for (const [id, parameter] of parameters) {
    const match = /^UID_OBJ_([0-9A-Fa-f]{4})$/.exec(id);
    if (!match) {
      continue;
    }
    const entry = createEntry({
      index: Number.parseInt(match[1], 16),
      name: directText(parameter, 'label') || `Object ${match[1].toUpperCase()}`,
    });
    applyParameter(entry, parameter, typeDefs);
    document.objects.push(entry);
  }
  for (const [id, parameter] of parameters) {
    const match = /^UID_SUB_([0-9A-Fa-f]{4})([0-9A-Fa-f]{2})$/.exec(id);
    if (!match) {
      continue;
    }
    const parent = document.objects.find((object) => object.index === Number.parseInt(match[1], 16));
    if (!parent) {
      continue;
    }
    const subIndex = Number.parseInt(match[2], 16);
    const sub = createEntry({
      index: parent.index,
      subIndex,
      name: directText(parameter, 'label') || `Sub ${hex2(subIndex)}`,
      objectType: 'VAR',
    });
    applyParameter(sub, parameter, typeDefs);
    parent.subObjects.push(sub);
    if (parent.objectType === 'VAR') {
      parent.objectType = 'RECORD';
    }
  }
}

function applyParameter(
  entry: OdEntry,
  parameter: Element,
  typeDefs: Map<string, DataTypeName | null>,
): void {
  const description = directText(parameter, 'description');
  if (description) {
    entry.description = description;
  }
  const label = directText(parameter, 'label');
  if (!entry.name && label) {
    entry.name = label;
  }
  const access = NETWORK_ACCESS[parameter.getAttribute('access') ?? ''];
  if (access) {
    entry.access = access;
  }
  const dataType = parameterDataType(parameter, typeDefs, entry.defaultValue);
  if (dataType) {
    entry.dataType = dataType;
  }
  const defaultValue = child(parameter, 'defaultValue');
  if (defaultValue) {
    entry.defaultValue = defaultValue.getAttribute('value') ?? (defaultValue.textContent ?? '').trim();
    if (entry.dataType === 'OCTET_STRING' && entry.defaultValue === '') {
      entry.dataType = 'DOMAIN';
    }
  }
  const limits = readLimits(parameter);
  if (limits.low != null) {
    entry.lowLimit = limits.low;
  }
  if (limits.high != null) {
    entry.highLimit = limits.high;
  }
  const actual = child(parameter, 'actualValue');
  if (actual) {
    entry.actualValue = actual.getAttribute('value') ?? (actual.textContent ?? '').trim();
  }
  const denotation = child(parameter, 'denotation');
  if (denotation) {
    entry.denotation = directText(denotation, 'label') || directText(denotation, 'description') || (denotation.textContent ?? '').trim();
  }
  for (const property of children(parameter, 'property')) {
    const name = property.getAttribute('name') ?? '';
    const value = property.getAttribute('value') ?? '';
    switch (name) {
      case 'CO_disabled':
        entry.disabled = value === 'true';
        break;
      case 'CO_countLabel':
        entry.countLabel = value;
        break;
      case 'CO_storageGroup':
        entry.storageGroup = value || 'RAM';
        break;
      case 'CO_flagsPDO':
        entry.flagsPdo = value === 'true';
        break;
      case 'CO_accessSRDO':
        entry.accessSrdo = srdoFrom(value);
        break;
      case 'CO_stringLengthMin':
        entry.stringLengthMin = Number(value) || 0;
        break;
      default:
        break;
    }
  }
}

function parameterDataType(
  parameter: Element,
  typeDefs: Map<string, DataTypeName | null>,
  fallbackDefault: string,
): DataTypeName | null {
  const direct = directType(parameter);
  if (direct) {
    if (direct.tag === 'BITSTRING') {
      const defaultValue = child(parameter, 'defaultValue');
      const value = defaultValue ? (defaultValue.getAttribute('value') ?? '') : fallbackDefault;
      return value === '' ? 'DOMAIN' : 'OCTET_STRING';
    }
    return direct.type;
  }
  const ref = child(parameter, 'dataTypeIDRef')?.getAttribute('uniqueIDRef');
  if (!ref || !typeDefs.has(ref)) {
    return null;
  }
  return typeDefs.get(ref) ?? null;
}

function readLimits(parameter: Element): { low: string | null; high: string | null } {
  const allowed = child(parameter, 'allowedValues');
  if (!allowed) {
    return { low: null, high: null };
  }
  const min = allElements(allowed, 'minValue')[0];
  const max = allElements(allowed, 'maxValue')[0];
  return {
    low: min ? (min.getAttribute('value') ?? '') : '',
    high: max ? (max.getAttribute('value') ?? '') : '',
  };
}

function parameterLines(entry: OdEntry, parent: OdEntry | null, level: number): string[] {
  const complex = parent == null && (entry.objectType === 'ARRAY' || entry.objectType === 'RECORD');
  const id = parent
    ? `UID_SUB_${hex4(entry.index)}${hex2(entry.subIndex)}`
    : `UID_OBJ_${hex4(entry.index)}`;
  const pad = '  '.repeat(level);
  const lines = [`${pad}<q1:parameter uniqueID="${id}"${accessAttribute(entry, parent, complex)}>`];
  if (entry.description) {
    lines.push(`${pad}  <description lang="en">${esc(entry.description)}</description>`);
  } else {
    lines.push(`${pad}  <label lang="en">${esc(entry.name)}</label>`);
  }
  if (complex && entry.objectType === 'ARRAY') {
    lines.push(`${pad}  <q1:dataTypeIDRef uniqueIDRef="UID_ARR_${hex4(entry.index)}" />`);
  } else if (complex) {
    lines.push(`${pad}  <q1:dataTypeIDRef uniqueIDRef="UID_REC_${hex4(entry.index)}" />`);
  } else {
    lines.push(`${pad}  <${typeTag(entry.dataType)} />`);
  }
  if (entry.defaultValue) {
    lines.push(`${pad}  <q1:defaultValue value="${esc(entry.defaultValue)}" />`);
  }
  if (entry.lowLimit || entry.highLimit) {
    lines.push(
      `${pad}  <q1:allowedValues>`,
      `${pad}    <q1:range>`,
      `${pad}      <q1:minValue value="${esc(entry.lowLimit)}" />`,
      `${pad}      <q1:maxValue value="${esc(entry.highLimit)}" />`,
      `${pad}    </q1:range>`,
      `${pad}  </q1:allowedValues>`,
    );
  }
  if (entry.actualValue) {
    lines.push(`${pad}  <q1:actualValue value="${esc(entry.actualValue)}" />`);
  }
  if (entry.denotation) {
    lines.push(
      `${pad}  <q1:denotation>`,
      `${pad}    <label lang="en">${esc(entry.denotation)}</label>`,
      `${pad}  </q1:denotation>`,
    );
  }
  lines.push(...propertyLines(entry, level + 1));
  lines.push(`${pad}</q1:parameter>`);
  return lines;
}

function propertyLines(entry: OdEntry, level: number): string[] {
  const properties: [string, string][] = [];
  if (entry.disabled) {
    properties.push(['CO_disabled', 'true']);
  }
  if (entry.countLabel) {
    properties.push(['CO_countLabel', entry.countLabel]);
  }
  if (entry.storageGroup && entry.storageGroup !== 'RAM') {
    properties.push(['CO_storageGroup', entry.storageGroup]);
  }
  if (entry.flagsPdo) {
    properties.push(['CO_flagsPDO', 'true']);
  }
  if (entry.accessSrdo !== 'no') {
    properties.push(['CO_accessSRDO', entry.accessSrdo]);
  }
  if (entry.stringLengthMin) {
    properties.push(['CO_stringLengthMin', String(entry.stringLengthMin)]);
  }
  const pad = '  '.repeat(level);
  return properties.map(([name, value]) => `${pad}<q1:property name="${esc(name)}" value="${esc(value)}" />`);
}

function accessAttribute(entry: OdEntry, parent: OdEntry | null, complex: boolean): string {
  if (complex) {
    return '';
  }
  let access = entry.access;
  if (access === 'unknown' && parent?.objectType === 'ARRAY' && parent.access !== 'unknown') {
    access = parent.access;
  }
  return access === 'unknown' || access === 'read' ? '' : ` access="${access}"`;
}

function arrayElementType(entry: OdEntry): DataTypeName {
  if (entry.dataType !== 'UNKNOWN') {
    return entry.dataType;
  }
  return sortedSubs(entry).find((sub) => sub.subIndex > 0 && sub.dataType !== 'UNKNOWN')?.dataType ?? 'UNSIGNED32';
}

function typeTag(dataType: DataTypeName): string {
  switch (dataType) {
    case 'BOOLEAN':
      return 'BOOL';
    case 'INTEGER8':
      return 'SINT';
    case 'INTEGER16':
      return 'INT';
    case 'INTEGER32':
      return 'DINT';
    case 'INTEGER64':
      return 'LINT';
    case 'UNSIGNED8':
      return 'USINT';
    case 'UNSIGNED16':
      return 'UINT';
    case 'UNSIGNED32':
      return 'UDINT';
    case 'UNSIGNED64':
      return 'ULINT';
    case 'REAL32':
      return 'REAL';
    case 'REAL64':
      return 'LREAL';
    case 'VISIBLE_STRING':
      return 'STRING';
    case 'UNICODE_STRING':
      return 'WSTRING';
    case 'DOMAIN':
    case 'OCTET_STRING':
    case 'INTEGER24':
    case 'INTEGER40':
    case 'INTEGER48':
    case 'INTEGER56':
    case 'UNSIGNED24':
    case 'UNSIGNED40':
    case 'UNSIGNED48':
    case 'UNSIGNED56':
    case 'TIME_OF_DAY':
    case 'TIME_DIFFERENCE':
      return 'BITSTRING';
    default:
      return 'DINT';
  }
}

