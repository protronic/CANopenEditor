function stamp(date: string, time: string, now: Date): { date: string; time: string } {
  return {
    date: date || formatDate(now),
    time: time || formatTime(now),
  };
}

function sortedSubs(entry: OdEntry): OdEntry[] {
  return [...entry.subObjects].sort((a, b) => a.subIndex - b.subIndex);
}

function adjustAccess(access: AccessType, pdoMapping: PdoMapping): AccessType {
  if (access !== 'readWrite') {
    return access;
  }
  if (pdoMapping === 'RPDO') {
    return 'readWriteOutput';
  }
  if (pdoMapping === 'TPDO') {
    return 'readWriteInput';
  }
  return access;
}

function objectTypeFrom(value: string | null): ObjectTypeName {
  if (!value) {
    return 'VAR';
  }
  const numeric = Number(value);
  if (Number.isInteger(numeric) && OBJECT_TYPE_BY_CODE[numeric]) {
    return OBJECT_TYPE_BY_CODE[numeric];
  }
  const names: ObjectTypeName[] = ['NULL', 'DOMAIN', 'DEFTYPE', 'DEFSTRUCT', 'VAR', 'ARRAY', 'RECORD'];
  return names.find((name) => name === value) ?? 'VAR';
}

function dataTypeFromAttribute(value: string | null): DataTypeName {
  if (!value) {
    return 'UNKNOWN';
  }
  const named = DATA_TYPE_BY_CODE[Number.parseInt(value, 16)];
  return named ?? 'UNKNOWN';
}

function pdoFrom(value: string | null): PdoMapping {
  if (value && PDO_VALUES.has(value as PdoMapping)) {
    return value as PdoMapping;
  }
  return 'no';
}

function srdoFrom(value: string): SrdoAccess {
  if (value === 'tx' || value === 'rx' || value === 'trx') {
    return value;
  }
  return 'no';
}

function directType(element: Element): { tag: string; type: DataTypeName } | null {
  for (const node of Array.from(element.children)) {
    const type = TYPE_TAGS[node.localName];
    if (type) {
      return { tag: node.localName, type };
    }
  }
  return null;
}

function profileKind(profile: Element, body: Element): 'device' | 'network' | 'other' {
  const classId = (child(child(profile, 'ProfileHeader') ?? profile, 'ProfileClassID')?.textContent ?? '').trim();
  const type = xsiType(body);
  if (classId === 'Device' || type.includes('ProfileBody_Device') || child(body, 'DeviceIdentity')) {
    return 'device';
  }
  if (classId === 'CommunicationNetwork' || type.includes('CommunicationNetwork') || first(body, 'CANopenObjectList')) {
    return 'network';
  }
  return 'other';
}

function xsiType(element: Element): string {
  return element.getAttribute('xsi:type')
    ?? element.getAttributeNS('http://www.w3.org/2001/XMLSchema-instance', 'type')
    ?? '';
}

function parseHex(value: string | null): number | null {
  if (!value) {
    return null;
  }
  const hex = value.trim().replace(/^0x/i, '').replace(/\s+/g, '');
  if (!/^[0-9a-fA-F]{1,8}$/.test(hex)) {
    return null;
  }
  const parsed = Number.parseInt(hex, 16);
  return parsed <= 0xffffffff ? parsed : null;
}

function numberAttr(element: Element, name: string, fallback: number): number {
  const value = element.getAttribute(name);
  if (value == null || value === '') {
    return fallback;
  }
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : fallback;
}

function boolAttr(element: Element, name: string, fallback: boolean): boolean {
  const value = element.getAttribute(name);
  if (value == null) {
    return fallback;
  }
  return value === 'true' || value === '1';
}

function directText(element: Element, name: string): string {
  const nodes = children(element, name);
  if (nodes.length === 0) {
    return '';
  }
  const preferred = nodes.find((node) => (node.getAttribute('lang') ?? 'en') === 'en') ?? nodes[0];
  return (preferred.textContent ?? '').trim();
}

function child(element: Element, name: string): Element | null {
  for (const node of Array.from(element.children)) {
    if (node.localName === name) {
      return node;
    }
  }
  return null;
}

function children(element: Element, name: string): Element[] {
  return Array.from(element.children).filter((node) => node.localName === name);
}

function first(element: Element, name: string): Element | null {
  return allElements(element, name)[0] ?? null;
}

function allElements(root: Document | Element, name: string): Element[] {
  const result: Element[] = [];
  const nodes = root.getElementsByTagName('*');
  for (let index = 0; index < nodes.length; index += 1) {
    const element = nodes.item(index);
    if (element?.localName === name) {
      result.push(element);
    }
  }
  return result;
}

function esc(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

